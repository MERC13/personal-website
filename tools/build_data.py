"""Write assets/data.js, the data behind the page's interactive demos.

Usage: python -I tools/build_data.py
Reads tools/data/*.json and penguins.csv; the page never reads those files directly.
"""
import csv
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "tools" / "data"


def load(name):
    return json.loads((DATA / name).read_text(encoding="utf-8"))


cae = load("cae_forest.json")
forest = {
    "repo": cae["source"]["repo"],
    "commit": cae["source"]["commit"],
    "min": cae["min"],
    "max": cae["max"],
    "ticks": cae["ticks"],
    "groups": {g["id"]: g["label"] for g in cae["groups"]},
    "rows": [
        {
            "row": r["row"],
            "group": r["group"],
            "window": r["window"],
            "chooser": r["chooser"],
            "n": r["n"],
            "verdict": r["verdict"],
            "marks": [[m["label"], m["est"], m["lo"], m["hi"]] for m in r["marks"]],
            "lines": r["lines"],
        }
        for r in cae["rows"]
    ],
}

st = load("steer_prompts.json")
steer = {
    "repo": st["source"]["repo"],
    "commit": st["source"]["commit"],
    "threshold": st["spread_threshold"],
    "categories": st["categories"],
    "tasks": [
        {
            "title": p["title"],
            "set": p["set"],
            "gate": p["gate"],
            "headroom": p["headroom"],
            "k": p["k"],
            "n": p["n"],
            "prompts": [[q["cat"], q["prompt"], q["k"], q["n"]] for q in p["prompts"]],
        }
        for p in st["panels"]
    ],
}

penguins = []
with open(DATA / "penguins.csv", encoding="utf-8") as f:
    for r in csv.DictReader(f):
        if r["bill_length_mm"] and r["flipper_length_mm"]:
            penguins.append([float(r["bill_length_mm"]), float(r["flipper_length_mm"]), r["species"][0]])

out = (
    "/* Generated by tools/build_data.py; do not edit by hand. */\n"
    "window.SITE_DATA = "
    + json.dumps({"forest": forest, "steer": steer, "penguins": penguins}, ensure_ascii=False, separators=(",", ":"))
    + ";\n"
)
(ROOT / "assets" / "data.js").write_text(out, encoding="utf-8", newline="\n")
sys.stdout.reconfigure(encoding="utf-8")
print(f"assets/data.js: {len(out):,} bytes, {len(forest['rows'])} forest rows, {len(steer['tasks'])} tasks, {len(penguins)} penguins")
